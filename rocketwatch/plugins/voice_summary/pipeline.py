import asyncio
import io
import logging
import re
from datetime import UTC, date, datetime
from pathlib import Path

from openai import AsyncOpenAI, omit
from pydantic import BaseModel, Field

from rocketwatch.utils.config import STTConfig
from rocketwatch.utils.llm import LLMProvider

log = logging.getLogger("rocketwatch.voice_summary.pipeline")

SUMMARY_CHAR_LIMIT = 3800
SUMMARY_MAX_TOKENS = 16384
MAX_CONCURRENT_TRANSCRIPTIONS = 4

GLOSSARY = (
    # Rocket Pool
    "Rocket Pool", "rETH", "RPL", "minipool", "megapool", "Smartnode", "node operator",
    "oDAO", "pDAO", "Protocol DAO", "Security Council", "RPIP", "Smoothing Pool",
    "Saturn", "Houston", "Atlas", "Redstone", "RocketDash", "Rocket Watch", "GMC", "IMC",
    # Ethereum staking
    "Ethereum", "ETH", "validator", "beacon chain", "consensus layer", "execution layer",
    "attestation", "slashing", "withdrawal credentials", "0x01", "0x02", "MEV-Boost",
    "Commit-Boost", "relay", "ePBS", "blobs", "EIP", "Lido", "stETH", "EigenLayer",
    "restaking",
    # upgrades and testnets
    "Glamsterdam", "Fusaka", "Pectra", "Dencun", "Hegota", "Hoodi", "Sepolia", "Holesky",
    "Ephemery", "devnet",
    # tools and services
    "Immunefi", "Kurtosis", "Forkcast",
    # clients
    "Geth", "Nethermind", "Besu", "Reth", "Erigon",
    "Lighthouse", "Prysm", "Teku", "Nimbus", "Lodestar",
)  # fmt: skip

SUMMARIZE_SYSTEM_PROMPT = """\
You are summarizing a Rocket Pool community call for Discord server members who missed it. \
In under a minute of reading, they want to know what happened and whether any of it affects \
them: protocol changes, governance votes, releases, deadlines, and things they may need to do.

Structure:
- Start with a bold **TL;DR** heading and 1-3 short bullets with the most important \
takeaways.
- Then one bold heading per major topic, in the order discussed, followed by the transcript \
timestamp where it starts, e.g. **Saturn upgrade timeline** (12:40). Readers use these \
timestamps to jump to that part of the attached recording. Under each heading, give bullets \
covering what was said or proposed, decisions reached, disagreements and who held which \
position, and anything left unresolved. Give the most space to what affects readers: votes, \
deadlines, releases, and changes for node operators or rETH holders.
- If other notable items didn't earn their own topic, add an **Also mentioned** section with \
one short bullet each.
- End with **Action Items**: each concrete next step someone committed to, with its owner, \
plus anything the community was asked to do (vote, nominate, give feedback), with where to \
do it and the deadline if one was given (don't mention missing deadlines). Omit this \
section only if there are none.

Make every bullet carry information. Prefer specifics over generalities: numbers, dates, \
versions, RPIP numbers, and the names of proposals, tools and teams. "Discussed the Saturn \
timeline" tells the reader nothing; "Saturn is targeted for mainnet in Q3, pending a second \
audit" does. Skip greetings, small talk, audio troubleshooting, and tangents that went \
nowhere. Give equal attention to all parts of the call, regardless of when they occurred.

Attribute proposals, commitments and opposing views to speakers, but state everything \
else as plain fact rather than starting each bullet with "X said". When referring to a \
participant listed in the roster, write their handle token (e.g. `@1`, `@2`) exactly as \
shown in the roster instead of their display name. Only use handles that appear in the \
roster; refer to anyone else by name.

The transcript is machine-generated by speech-to-text and contains transcription errors, \
especially in names and project terms. When a word is clearly a mishearing of a known term \
(e.g. from the glossary, if one is provided), use the correct term. Do not guess beyond that \
or invent content that isn't in the transcript. Speakers sometimes refer to things on a shared \
screen that you can't see; leave such details out rather than guess what was shown.

The summary stays in the channel and is read days later, so turn relative dates ("in five \
days", "this Friday") into calendar dates using the call date when the result is unambiguous.

HARD LIMIT: the summary must be at most 400 words; aim for 200-350, and less for short \
calls. Use 2-4 bullets per topic, collapse related points into single bullets, and \
tighten wording. One concise sentence per bullet — no sub-bullets, no long \
paragraphs.

If the transcript contains no substantive discussion worth summarizing \
(e.g. only greetings, idle chatter, silence, or people joining/leaving), \
set has_content to false and leave summary empty.

The `summary` field must be a plain markdown string — bold section headings \
followed by bullet points, with no bold inside bullets. Do NOT emit JSON, arrays, or \
nested objects inside it."""

SHORTEN_SYSTEM_PROMPT = """\
You will be given a structured summary that is too long for its destination. \
Rewrite it to be shorter while preserving the same section structure and the most \
important facts, decisions, and action items. Drop minor details, merge related \
bullets, and tighten wording. Keep bullet points, section headers, and the \
timestamps after topic headers. \
Preserve any handle tokens of the form `@1`, `@2`, etc. exactly as they appear. \
Return only the shortened summary, nothing else."""


class SummaryResult(BaseModel):
    has_content: bool = Field(
        description="Whether the transcript contains substantive discussion worth posting."
    )
    summary: str = Field(
        default="",
        description="The structured summary of the transcript.",
    )


class _Segment:
    """A timestamped piece of transcript from a single speaker."""

    __slots__ = ("speaker", "start", "text")

    def __init__(self, start: float, speaker: str, text: str) -> None:
        self.start = start
        self.speaker = speaker
        self.text = text


class TranscriptionPipeline:
    def __init__(
        self,
        stt_config: STTConfig,
        llm_provider: LLMProvider,
    ) -> None:
        self._stt = stt_config
        self._llm = llm_provider
        self._client: AsyncOpenAI | None = None
        self._slots = asyncio.Semaphore(MAX_CONCURRENT_TRANSCRIPTIONS)

    def _get_client(self) -> AsyncOpenAI:
        if self._client is None:
            self._client = AsyncOpenAI(api_key=self._stt.api_key)
        return self._client

    async def close(self) -> None:
        if self._client is not None:
            await self._client.close()
            self._client = None

    async def transcribe_wav(self, wav_path: Path) -> str:
        """Transcribe a single WAV file."""
        async with self._slots:
            buf = io.BytesIO(wav_path.read_bytes())
            buf.name = wav_path.name

            response = await self._get_client().audio.transcriptions.create(
                model=self._stt.model,
                language="en",
                file=buf,
                response_format="json",
                # other models reject the parameter
                keywords=GLOSSARY
                if self._stt.model.startswith("gpt-transcribe")
                else omit,
            )
        return response.text.strip()

    @staticmethod
    def format_transcript(
        segments: dict[int, list[tuple[float, str]]],
        usernames: dict[int, str],
    ) -> str:
        """Sort all segments by timestamp and format as a transcript string.

        Args:
            segments: user_id -> [(offset_seconds, text), ...]
            usernames: user_id -> display name
        """
        entries: list[_Segment] = []
        for user_id, user_segments in segments.items():
            speaker = usernames.get(user_id, f"User {user_id}")
            for start, text in user_segments:
                entries.append(_Segment(start=start, speaker=speaker, text=text))

        entries.sort(key=lambda s: s.start)

        lines: list[str] = []
        for seg in entries:
            minutes = int(seg.start) // 60
            seconds = int(seg.start) % 60
            lines.append(f"[{minutes}:{seconds:02d}] {seg.speaker}: {seg.text}")

        return "\n".join(lines)

    async def summarize(
        self,
        transcript: str,
        usernames: dict[int, str],
        call_date: date | None = None,
    ) -> str | None:
        """Summarize a transcript using the configured LLM.

        Returns None if the LLM determines there is no substantive content.
        """
        # Assign a small positional handle to each participant so the model
        # can reference them with short tokens (@1, @2, ...) rather than
        # copying long Discord IDs verbatim.
        handle_to_id = {i + 1: uid for i, uid in enumerate(usernames)}
        roster = "\n".join(
            f"- @{i} refers to {usernames[uid]}" for i, uid in handle_to_id.items()
        )
        call_date = call_date or datetime.now(UTC).date()
        user_message = (
            f"Call date: {call_date:%A, %B %-d, %Y}\n\n"
            "Participant roster — when referring to any of these people in the "
            "summary, write the handle token instead of their name:\n"
            f"{roster}\n\n"
            f"Glossary of terms used in these calls: {', '.join(GLOSSARY)}\n\n"
            f"Summarize this community call transcript:\n\n{transcript}"
        )
        result = await self._llm.complete_structured(
            SUMMARIZE_SYSTEM_PROMPT,
            user_message,
            SummaryResult,
            max_tokens=SUMMARY_MAX_TOKENS,
        )
        if not result.has_content:
            return None

        summary = result.summary
        for attempt in range(3):
            expanded = self._expand_handles(summary, handle_to_id, usernames)
            if len(expanded) <= SUMMARY_CHAR_LIMIT or attempt == 2:
                break
            # handles grow into longer mentions after shortening, so budget for that
            budget = SUMMARY_CHAR_LIMIT - (len(expanded) - len(summary))
            log.info(
                f"Summary is {len(expanded)} chars, shortening (attempt {attempt + 1})"
            )
            summary = await self._llm.complete(
                SHORTEN_SYSTEM_PROMPT,
                f"Shorten this summary to under {budget} characters "
                f"(currently {len(summary)}):\n\n{summary}",
                max_tokens=SUMMARY_MAX_TOKENS,
            )

        return self._truncate_lines(expanded, SUMMARY_CHAR_LIMIT)

    @staticmethod
    def _truncate_lines(text: str, limit: int) -> str:
        """Cut text to at most limit chars at a line break, so no mention is split
        and no heading is left without its bullets."""
        if len(text) <= limit:
            return text
        lines = text[:limit].splitlines()[:-1] or [text[:limit]]
        while len(lines) > 1 and not lines[-1].lstrip().startswith("-"):
            lines.pop()
        return "\n".join(lines)

    @staticmethod
    def _expand_handles(
        text: str, handle_to_id: dict[int, int], usernames: dict[int, str]
    ) -> str:
        """Replace @N handles with real Discord mentions; unknown handles get the name or are dropped."""

        def repl(match: re.Match[str]) -> str:
            handle = int(match.group(1))
            uid = handle_to_id.get(handle)
            if uid is not None:
                return f"<@{uid}>"
            return "someone"

        return re.sub(r"@(\d+)", repl, text)

    async def process_users(
        self,
        user_segments: dict[int, list[tuple[float, Path]]],
        usernames: dict[int, str],
    ) -> tuple[str, str | None]:
        """Full pipeline with speaker labels. Returns (transcript, summary).

        Summary is None if the LLM determines there is no substantive content.
        """
        segments: dict[int, list[tuple[float, str]]] = {}
        for user_id, wav_list in user_segments.items():
            user_segs: list[tuple[float, str]] = []
            for offset, wav_path in wav_list:
                if text := await self.transcribe_wav(wav_path):
                    user_segs.append((offset, text))
            segments[user_id] = user_segs

        transcript = self.format_transcript(segments, usernames)
        summary = await self.summarize(transcript, usernames)
        return transcript, summary
